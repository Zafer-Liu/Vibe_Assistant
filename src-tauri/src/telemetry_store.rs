pub(crate) fn normalize_l1_memory_type(value: &str) -> &'static str {
    match value.trim().to_ascii_lowercase().as_str() {
        "summary" => "summary",
        "fact" | "conversation" => "fact",
        "decision" => "decision",
        "constraint" => "constraint",
        "preference" | "preference_candidate" => "preference_candidate",
        "open_item" => "open_item",
        _ => "fact",
    }
}

/// 用户自定义记忆的归属层级：按 id 前缀判定，`local-user-l2:` 属于
/// 工作记忆；`local-user-l3:` 与旧版 `local-user:` 属于长期 Profile。
pub(crate) fn user_defined_memory_scope(id: &str) -> &'static str {
    if id.starts_with("local-user-l2:") {
        "l2"
    } else {
        "l3"
    }
}

pub(crate) fn validate_l1_durability(value: &str) -> Result<&'static str, String> {
    match value.trim().to_ascii_lowercase().as_str() {
        "session" => Ok("session"),
        "short_term" => Ok("short_term"),
        "long_term" => Ok("long_term"),
        "undetermined" | "unknown" | "uncertain" | "无法判断" | "不确定" => {
            Err("durability 无法判断，必须由模型明确标为 session、short_term 或 long_term".into())
        }
        _ => Err(format!(
            "durability 格式无效：{value:?}；只能是 session、short_term 或 long_term"
        )),
    }
}

