/// Range-scoped analytics generated by SQLite, rather than a browser-side
/// filter over an arbitrary latest-N sample. This keeps 30-day/all-history
/// totals correct even when the ledger contains many thousands of records.
#[derive(Clone, Serialize)]
#[serde(rename_all = "snake_case")]
pub struct TelemetryUsageAnalytics {
    pub record_count: i64,
    pub input_tokens: i64,
    pub output_tokens: i64,
    pub cached_tokens: i64,
    /// Tokens contributed by rows whose origin starts with `estimated` —
    /// transparent local estimates, not provider counters.
    pub estimated_tokens: i64,
    /// False 当所选范围只有估算/远端总量行：它们没有缓存计数，
    /// 前端据此把「缓存命中率」显示为不可用而不是误导性的 0.0%。
    pub cache_capable: bool,
    pub records: Vec<TelemetryUsageRecord>,
    pub truncated_records: bool,
    pub buckets: Vec<TelemetryUsageBucket>,
    /// Full-range local-time activity matrix, independent of the records cap.
    pub heatmap: Vec<TelemetryUsageHeatCell>,
    /// Full-range totals grouped by source/model for user-configured cost rules.
    pub cost_groups: Vec<TelemetryUsageCostGroup>,
    pub sources: Vec<String>,
}

